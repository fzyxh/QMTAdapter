"""Query only a generated, guarded Python 3.12 migration test bridge."""

import argparse
import inspect
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from qmt_adapter import QmtClient


INDICES = ['000001.SH', '399001.SZ', '899050.BJ']


def run(config_path, report_path):
    config = json.loads(Path(config_path).read_text(encoding='ascii'))
    if config.get('python312_readonly_test') is not True:
        raise ValueError('Use only the configuration generated by prepare_python312_readonly_test.py')
    report = {'observed_at': datetime.now(timezone.utc).isoformat(), 'checks': [],
              'limitations': ['Read-only broker queries; no transaction lifecycle or live DELTA verification.']}
    secrets = [config.get('auth_token', '')]

    def check(name, operation, summarize):
        started = time.perf_counter()
        try:
            result = operation()
            item = {'name': name, 'status': 'PASS', 'result': summarize(result)}
        except Exception as exc:
            message = str(exc)
            for secret in secrets:
                if secret:
                    message = message.replace(secret, '<REDACTED>')
            item = {'name': name, 'status': 'FAIL', 'error_type': type(exc).__name__, 'message': message}
            result = None
        item['elapsed_ms'] = round((time.perf_counter() - started) * 1000, 3)
        report['checks'].append(item)
        print(json.dumps(item, ensure_ascii=True))
        return result

    def count(result):
        if not isinstance(result, dict) or not isinstance(result.get('items'), list):
            raise ValueError('Query did not return items/count')
        return {'count': result.get('count'), 'empty': len(result['items']) == 0}

    def health_summary(value):
        if not value.get('readonly_test', {}).get('enabled'):
            raise ValueError('Connected server is not the guarded read-only test')
        runtime = value.get('runtime', {})
        if (runtime.get('adapter_version') != '0.10.1' or runtime.get('protocol_version') != 9
                or not runtime.get('python_version', '').startswith('3.12.')
                or runtime.get('python_implementation') != 'CPython' or runtime.get('pointer_bits') != 64):
            raise ValueError('Unexpected server runtime: ' + json.dumps(runtime))
        if value.get('status') != 'OK':
            raise ValueError('Bridge health is degraded')
        return {'runtime': runtime, 'active_client_count': value['active_client_count'],
                'timer_tick_count': value['timer_tick_count'], 'status': value['status']}

    try:
        with QmtClient(config_path=config_path, client_id='python312-readonly-smoke') as client:
            accounts = client.hello.get('accounts', [])
            if len(accounts) != 1:
                raise ValueError('Exactly one test account must be configured in the QMT test loader')
            account_id = accounts[0]['account_id']
            secrets.append(account_id)
            initial = check('health.initial', client.health, health_summary)
            if initial is None:
                raise ValueError('Runtime validation failed; remaining queries were not started')
            if client.connect() is not client:
                raise ValueError('Repeated connect changed the client')

            def account_summary(value):
                result = count(value)
                if not value['items']:
                    raise ValueError('Account query returned no account object')
                raw = value['items'][0].get('raw', {})
                status = raw.get('m_strStatus')
                if status != '\u767b\u5f55\u6210\u529f':
                    raise ValueError('Account status is not login success: ' + str(status))
                result.update(native_status=status, trading_date=raw.get('m_strTradingDate'),
                              has_total_asset=value['items'][0].get('total_asset') is not None)
                if not result['has_total_asset']:
                    raise ValueError('Account total asset is missing')
                return result

            check('account.get', lambda: client.get_account(account_id, include_raw=True), account_summary)
            check('position.list', lambda: client.list_positions(account_id, include_raw=True), count)
            check('order.list', lambda: client.list_orders(account_id=account_id), count)
            if 'scope' in inspect.signature(client.list_orders).parameters:
                check('order.list.ACCOUNT', lambda: client.list_orders(account_id, scope='ACCOUNT'), count)
            for scope in ('ACCOUNT', 'ADAPTER'):
                check('trade.list.' + scope, lambda scope=scope: client.list_trades(account_id, scope=scope), count)

            def quotes_summary(value):
                result = count(value)
                result['error_count'] = value.get('error_count', 0)
                if result['error_count'] or result['count'] != len(INDICES):
                    raise ValueError('One or more index quotes were unavailable')
                return result

            check('quote.list', lambda: client.get_quotes(INDICES), quotes_summary)
            check('instrument.detail.list', lambda: client.get_instrument_details(INDICES), count)
            check('sector.instruments.list', lambda: client.list_sector_instruments('\u6caa\u6df1\u4eacA\u80a1'), count)
            check('new_issue.list', client.list_new_issues, count)
            check('new_issue.quota.get', lambda: client.get_new_issue_quota(account_id),
                  lambda value: {'limit_keys': sorted(value['limits']) if isinstance(value['limits'], dict) else [],
                                 'empty': not bool(value['limits'])})
            check('algo_order.list', lambda: client.list_algo_orders(account_id=account_id), count)
            for period in ('1m', '1d'):
                def bars_summary(value):
                    result = count(value)
                    result['row_counts'] = [item['count'] for item in value['items']]
                    result['last_timestamps'] = [item['timestamps'][-1] if item['timestamps'] else None for item in value['items']]
                    if not any(result['row_counts']):
                        raise ValueError('All local history results were empty; history data remains unverified')
                    return result
                check('market.history.' + period,
                      lambda period=period: client.get_bar_history(INDICES, period, count=3, timeout=15), bars_summary)
            check('market.daily.front_ratio',
                  lambda: client.get_daily_history(INDICES, count=3, adjustment='front_ratio', timeout=15), bars_summary)

            def two_clients():
                with QmtClient(config_path=config_path, client_id='python312-second-client') as second:
                    result = second.health()
                    health_summary(result)
                    if result['active_client_count'] < 2:
                        raise ValueError('Second command client was not observed')
                    return result
            check('command.two_clients', two_clients, health_summary)

            def quote_snapshot():
                try:
                    response = client.subscribe_whole_quote(
                        markets=['SH', 'SZ', 'BJ'], instrument_scope=None, include_instruments=INDICES,
                        mode='SNAPSHOT', push_interval_ms=100, chunk_size=2, initial_snapshot=True)
                    # Leave the quote reader unconsumed while a command query completes.
                    health_summary(client.health())
                    seen = set()
                    deadline = time.monotonic() + 5
                    while seen != set(INDICES) and time.monotonic() < deadline:
                        event = client.get_quote_event(timeout=max(0.01, deadline - time.monotonic()))
                        seen.update(item['instrument'] for item in event['items'])
                    if seen != set(INDICES):
                        raise ValueError('Initial snapshot did not cover all three indices')
                    return {'received_instruments': sorted(seen), 'initial_snapshot': response['initial_snapshot'],
                            'command_query_during_subscription': 'PASS'}
                finally:
                    client.unsubscribe_whole_quote()
            check('quote.snapshot_and_command', quote_snapshot, lambda value: value)
            final = check('health.final', client.health, health_summary)
            if final is not None and final['timer_tick_count'] <= initial['timer_tick_count']:
                report['checks'].append({'name': 'timer.progress', 'status': 'FAIL', 'message': 'QMT timer did not advance'})
    except Exception as exc:
        message = str(exc)
        for secret in secrets:
            if secret:
                message = message.replace(secret, '<REDACTED>')
        report['checks'].append({'name': 'session', 'status': 'FAIL', 'error_type': type(exc).__name__, 'message': message})
    report['status'] = 'PASS' if report['checks'] and all(c['status'] == 'PASS' for c in report['checks']) else 'FAIL'
    Path(report_path).write_text(json.dumps(report, ensure_ascii=True, indent=2) + '\n', encoding='ascii')
    print('REPORT=' + str(report_path))
    print('RESULT=' + report['status'])
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', required=True, help='Generated isolated test config; never the production config')
    parser.add_argument('--report', help='Output JSON path; default is readonly-smoke.json in the test root')
    args = parser.parse_args()
    report_path = args.report or Path(args.config).resolve().parent.parent / 'readonly-smoke.json'
    report = run(args.config, report_path)
    return 0 if report['status'] == 'PASS' else 1


if __name__ == '__main__':
    raise SystemExit(main())
